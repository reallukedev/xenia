//! Xenia's shared engine.
//!
//! Everything a Xenia app needs that isn't drawing pixels lives here: the Matrix client and its
//! sync, the room list and the rules for which conversation goes where, timelines already grouped
//! into runs of bubbles, rich text parsed into blocks, mentions, search, threads, encryption and
//! the decision of when something deserves a notification.
//!
//! Each platform's app (SwiftUI today; Jetpack Compose, WinUI or GTK later) renders what this
//! crate hands it and calls back into it. The apps never see the Matrix SDK. Three rules keep the
//! boundary clean:
//!
//! 1. **Data out, decisions in here.** Records crossing the boundary are view-ready: a room's
//!    scope and unread state, a message's place in its run, who has read what. If two platforms
//!    would otherwise write the same `if`, it belongs in this crate.
//! 2. **Words stay native.** No user-facing sentence is built here. Notes ("Maya joined") and
//!    previews ("Photo") cross as structured enums so each platform localizes them its own way.
//! 3. **Platform services come in through traits.** Secret storage is a callback interface the
//!    app implements (the Keychain on Apple platforms), never a platform API called from Rust.
//!
//! The Swift and Kotlin bindings are generated by UniFFI from the `#[uniffi::export]`
//! annotations; a Rust front end can use the same API directly.

